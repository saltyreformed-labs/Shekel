"""The one comparison of the schema the migration chain builds with the one the models build.

Finding plan#1858.  A database comes to head two ways: the deploy and the test template replay the
Alembic chain, and ``scripts/init_database.py`` builds a fresh one from the MODELS and stamps head.
The two must agree, or a fresh install holds a schema production does not, and a later migration
written against production's (dropping a key by its name, re-cutting a CHECK) fails on it or does
something else.  ``scripts/build_test_template.py`` said this drift "surfaces" in its build, and
nothing compared anything: a migration that dropped a column named in a multi-column CHECK, which
takes the CHECK with it, built green (measured in plan step X-bi-6-5's leaf 1).

Alembic's ``compare_metadata`` cannot be the comparison.  It reads neither a CHECK nor a partial
index's predicate (measured: ``TestTheTables`` in
``tests/test_models/test_a_transfer_side_s_payment_hangs_off_the_transfer.py``), and it matches a
foreign key by its columns, not its name (migration ``b4b588a49a0c``'s docstring; and
``pay_entries``' key, named apart on the two sides until plan#1858, passed
``tests/test_models/test_pay_entries_migration.py``'s comparison of that table).  So the models
are BUILT, each model schema into a scratch schema of its own through ``schema_translate_map``,
and PostgreSQL's own definitions of both builds are compared: what it would print for each
object, with the scratch schema's name written back as the real one.

Compared, in each schema the models declare (derived from the metadata, never listed):

* every table, view and partitioned table, by name and kind;
* every column: its type, collation, nullability, default or generation expression, and
  identity;
* every constraint (primary key, unique, foreign key, CHECK, exclusion), by name and definition;
* every index, by name and definition, a partial index's predicate included.

NOT compared, each for a stated reason:

* NOT NULL constraints by NAME.  PostgreSQL 18 records each as a constraint named
  ``<table>_<column>_not_null`` when the column is made, and never renames it when the table or
  column is; a model cannot name one.  Eight of the chain's carry a renamed table's or column's old
  name (measured 2026-10-27), which is no difference in the schema.  The column comparison carries
  the nullability itself.
* Triggers, constraint triggers and functions: no model declares one.  The infrastructure
  modules attach them on both paths, and :func:`scripts._template_checks.template_checks`
  counts every family but the posting and opening triggers (finding BAL-542).
* Sequences as objects of their own, column order, comments, grants and storage parameters: none
  is a rule a row is held to.  A serial's sequence IS compared by name, through its column's
  default (``nextval('<schema>.<sequence>'::regclass)``), so a table renamed while its sequence
  keeps the old name is a difference; an identity's would not be, and no model declares an
  identity column (2026-10-27).
* Any schema no model is in.  ``system`` is one: both paths build the audit infrastructure's
  ``audit_log`` there, and a database the chain built also holds the three snapshot tables
  migrations keep for their own downgrades (``transfer_twin_purge``, ``pre_origination_purge``,
  ``loan_due_date_backfill``), which no model declares.
"""

from __future__ import annotations

from typing import NamedTuple

from sqlalchemy import MetaData, text
from sqlalchemy.engine import Connection

#: The scratch schema a model schema ``S`` is built into is this prefix and ``S``.
_SCRATCH_PREFIX = "models_"

#: Kinds of object, in the order a report lists them.
_KINDS = ("table", "column", "constraint", "index")

_TABLES_SQL = """
SELECT n.nspname, c.relname,
       CASE c.relkind WHEN 'r' THEN 'table' WHEN 'p' THEN 'partitioned table'
            WHEN 'v' THEN 'view' WHEN 'm' THEN 'materialized view'
            ELSE 'foreign table' END
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = ANY(:schemas) AND c.relkind IN ('r', 'p', 'v', 'm', 'f')
"""

_COLUMNS_SQL = """
SELECT n.nspname, c.relname || '.' || a.attname,
       format_type(a.atttypid, a.atttypmod)
       || CASE WHEN a.attcollation <> ty.typcollation
               THEN ' COLLATE ' || quote_ident(co.collname) ELSE '' END
       || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END
       || CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
               WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END
       || CASE WHEN a.attgenerated <> ''
                    THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ')'
               WHEN d.adbin IS NOT NULL
                    THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid)
               ELSE '' END
FROM pg_attribute a
JOIN pg_class c ON c.oid = a.attrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
JOIN pg_type ty ON ty.oid = a.atttypid
LEFT JOIN pg_collation co ON co.oid = a.attcollation
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE n.nspname = ANY(:schemas) AND c.relkind IN ('r', 'p', 'v', 'm', 'f')
  AND a.attnum > 0 AND NOT a.attisdropped
"""

# contype 't' is a constraint trigger and 'n' a NOT NULL: the module docstring says why neither.
_CONSTRAINTS_SQL = """
SELECT n.nspname, c.relname || '.' || con.conname, pg_get_constraintdef(con.oid)
FROM pg_constraint con
JOIN pg_class c ON c.oid = con.conrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = ANY(:schemas) AND con.contype NOT IN ('t', 'n')
"""

_INDEXES_SQL = """
SELECT n.nspname, t.relname || '.' || i.relname, pg_get_indexdef(x.indexrelid)
FROM pg_index x
JOIN pg_class i ON i.oid = x.indexrelid
JOIN pg_class t ON t.oid = x.indrelid
JOIN pg_namespace n ON n.oid = i.relnamespace
WHERE n.nspname = ANY(:schemas)
"""


class Drift(NamedTuple):
    """One object the two builds disagree on.

    Attributes:
        kind: ``table``, ``column``, ``constraint`` or ``index``.
        name: ``schema.table`` for a table, ``schema.table.object`` for the rest.
        migrated: Its definition as the chain builds it, or None when the chain builds none.
        modelled: Its definition as the models build it, or None when the models build none.
    """

    kind: str
    name: str
    migrated: str | None
    modelled: str | None

    def describe(self) -> str:
        """Return one line naming the object and what each build makes of it."""
        return (
            f"{self.kind} {self.name}: the migrations build "
            f"{self.migrated or 'nothing'}; the models build {self.modelled or 'nothing'}"
        )


class SchemaDriftError(RuntimeError):
    """The migration chain at head and the models build different schemas.

    Attributes:
        drift: Every difference, in report order.
    """

    def __init__(self, drift: tuple[Drift, ...]) -> None:
        """Build the message from every difference.

        Args:
            drift: The differences; at least one.
        """
        self.drift = drift
        super().__init__(
            f"The migration chain at head and the models build different schemas "
            f"({len(drift)} difference(s)):\n"
            + "\n".join(f"  {item.describe()}" for item in drift)
            + "\nProduction's schema is the chain's.  Make each model declare what its "
            "migration built, or write the migration that builds what the model declares."
        )


def _catalog(
    connection: Connection, schemas: list[str], prefix: str,
) -> dict[tuple[str, str], str]:
    """Return every compared object in the *prefix*-ed copies of *schemas*.

    Args:
        connection: Where to read the catalog.
        schemas: The model schemas, by their real names.
        prefix: ``""`` for the migrated schemas, :data:`_SCRATCH_PREFIX` for the models' build.

    Returns:
        ``{(kind, real schema.name): definition}``, each definition with the scratch schemas'
        names written back as the real ones, so two builds that agree compare equal.
    """
    real = {f"{prefix}{schema}": schema for schema in schemas}
    found: dict[tuple[str, str], str] = {}
    for kind, sql in zip(_KINDS, (_TABLES_SQL, _COLUMNS_SQL, _CONSTRAINTS_SQL, _INDEXES_SQL)):
        for schema, name, definition in connection.execute(
            text(sql), {"schemas": list(real)},
        ):
            for scratch, schema_name in real.items():
                definition = definition.replace(f"{scratch}.", f"{schema_name}.")
            found[(kind, f"{real[schema]}.{name}")] = definition
    return found


def schema_drift(connection: Connection, metadata: MetaData) -> tuple[Drift, ...]:
    """Return every object the migrated schema and the models' build disagree on.

    Builds the models inside a SAVEPOINT it rolls back, so it leaves no scratch schema behind and
    the caller's own uncommitted work (a test's mutation) is what it compares against.  The
    connection's ``schema_translate_map`` is restored afterwards: SQLAlchemy 2 sets an execution
    option on a Connection IN PLACE, and a map left on it would point every later statement at a
    schema the rollback removed.

    Args:
        connection: A connection to a database the chain has brought to head.
        metadata: The models' metadata.

    Returns:
        The differences, ordered by kind (tables, columns, constraints, indexes) then name;
        empty when the two builds agree.
    """
    schemas = sorted({table.schema for table in metadata.tables.values()})
    migrated = _catalog(connection, schemas, "")
    earlier_map = connection.get_execution_options().get("schema_translate_map")
    savepoint = connection.begin_nested()
    try:
        for schema in schemas:
            connection.execute(text(f'CREATE SCHEMA "{_SCRATCH_PREFIX}{schema}"'))
        connection.execution_options(schema_translate_map={
            schema: f"{_SCRATCH_PREFIX}{schema}" for schema in schemas
        })
        metadata.create_all(bind=connection)
        modelled = _catalog(connection, schemas, _SCRATCH_PREFIX)
    finally:
        connection.execution_options(schema_translate_map=earlier_map)
        savepoint.rollback()
    return tuple(
        Drift(kind, name, migrated.get((kind, name)), modelled.get((kind, name)))
        for kind, name in sorted(
            migrated.keys() | modelled.keys(),
            key=lambda key: (_KINDS.index(key[0]), key[1]),
        )
        if migrated.get((kind, name)) != modelled.get((kind, name))
    )


def refuse_schema_drift(connection: Connection, metadata: MetaData) -> None:
    """Raise when the migrated schema and the models' build disagree on any compared object.

    Args:
        connection: A connection to a database the chain has brought to head.
        metadata: The models' metadata.

    Raises:
        SchemaDriftError: Naming every difference.
    """
    drift = schema_drift(connection, metadata)
    if drift:
        raise SchemaDriftError(drift)
