class TestOwnerEntrypointRun:
    """The owner's entrypoint, run: its command, whatever it is, runs as the owner under the
    deploy's configuration, and nothing else runs first but the wait."""

    def test_runs_its_command_as_the_owner_under_the_deploy_configuration(
        self, image: _Image,
    ) -> None:
        """A maintenance command (``docker compose run migrate python scripts/...``) starts
        with the owner's URL and ``FLASK_ENV=deploy`` over the stack's own, after the wait as
        the owner, and no deploy step runs first."""
        password = _password()

        result = image.run(OWNER_ENTRYPOINT, "record",
                           env={"OWNER_ROLE_PASSWORD": password, "FLASK_ENV": "production"})

        assert result.returncode == 0, result.stderr
        assert image.steps() == ["pg_isready", "record"]
        wait, started = image.calls()
        assert wait["args"] == ["-h", "db", "-p", "5432", "-U", "shekel_owner", "-q"]
        assert started["env"]["DATABASE_URL"] == _url("shekel_owner", password)
        assert started["env"]["FLASK_ENV"] == "deploy"

    def test_a_mounted_owner_password_file_wins_over_the_variable(
        self, image: _Image,
    ) -> None:
        """The owner's URL carries the mounted file's password, not the variable's."""
        mounted = _password()
        image.secret("owner_role_password", mounted)

        result = image.run(OWNER_ENTRYPOINT, "record",
                           env={"OWNER_ROLE_PASSWORD": _password()})

        assert result.returncode == 0, result.stderr
        assert image.calls()[-1]["env"]["DATABASE_URL"] == _url("shekel_owner", mounted)

    def test_refuses_without_the_owners_password(self, image: _Image) -> None:
        """No file and no variable: it stops by name before it waits or runs anything."""
        result = image.run(OWNER_ENTRYPOINT, "record")

        assert result.returncode == 1
        assert "the database owner's password is not set" in result.stderr
        assert image.calls() == []

    def test_refuses_without_a_command(self, image: _Image) -> None:
        """Run with nothing to run, it says so rather than exiting 0 having done nothing."""
        result = image.run(OWNER_ENTRYPOINT, env={"OWNER_ROLE_PASSWORD": _password()})

        assert result.returncode == 1
        assert "no command to run as the database owner" in result.stderr
        assert image.calls() == []


