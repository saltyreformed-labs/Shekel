class TestDeployRun:
    """The deploy, run as the migrate service runs it: under the owner's entrypoint."""

    def _deploy(self, image: _Image, **env: str) -> subprocess.CompletedProcess[str]:
        """Run the copy's deploy as the migrate service's command, with ``env``."""
        return image.run(OWNER_ENTRYPOINT, str(image.root / DEPLOY), env=env)

    def test_runs_its_four_steps_in_order_as_the_owner(self, image: _Image) -> None:
        """The schemas, the web login's grants, the one-transaction deploy and the first
        user's seed, in that order, each as the owner: ``psql`` logs in as ``shekel_owner``
        with the password in its environment and in none of its arguments, and each Python
        step builds the deploy's configuration on the owner's URL alone.  The sentinel is
        written once the seed has run."""
        password = _password()

        result = self._deploy(image, OWNER_ROLE_PASSWORD=password,
                              SEED_USER_EMAIL="owner@example.test")

        assert result.returncode == 0, result.stderr
        assert image.steps() == ["pg_isready", "init_db.sql", "init_db_role.sql",
                                 "init_database.py", "seed_user.py"]
        for call in image.calls()[1:3]:
            args = call["args"]
            assert args[args.index("-U") + 1] == "shekel_owner"
            assert args[args.index("-d") + 1] == "shekel"
            assert "ON_ERROR_STOP=1" in args
            assert call["env"]["PGPASSWORD"] == password
            assert not any(password in arg for arg in args), (
                "the owner's password is in psql's arguments, which any process in the "
                "container can read in /proc/<pid>/cmdline"
            )
        for call in image.calls()[3:]:
            assert call["env"]["FLASK_ENV"] == "deploy"
            assert call["env"]["DATABASE_URL"] == _url("shekel_owner", password)
            assert "DATABASE_URL_APP" not in call["env"]
        assert image.sentinel().is_file()

    def test_grants_the_web_login_its_privileges_in_one_transaction(
        self, image: _Image,
    ) -> None:
        """psql runs the grants file as one transaction (ruling plan#3534): its blanket grant
        re-opens UPDATE and DELETE on the posting ledger and its revoke closes them, and a
        deploy beside a serving app commits the two together, so no request ever runs between
        them.  ``test_provision_roles.py`` runs the file so on a real cluster."""
        result = self._deploy(image, OWNER_ROLE_PASSWORD=_password())

        assert result.returncode == 0, result.stderr
        ran = dict(zip(image.steps(), image.calls(), strict=True))
        assert "--single-transaction" in ran["init_db_role.sql"]["args"], (
            "scripts/deploy.sh runs init_db_role.sql a statement at a time: between its "
            "blanket GRANT and its REVOKE the web login holds UPDATE and DELETE on the ledger"
        )

    def test_skips_the_seed_when_its_sentinel_is_present(self, image: _Image) -> None:
        """A deploy after the first finds the sentinel and runs no seed."""
        image.state_dir.mkdir()
        image.sentinel().touch()

        result = self._deploy(image, OWNER_ROLE_PASSWORD=_password(),
                              SEED_USER_EMAIL="owner@example.test")

        assert result.returncode == 0, result.stderr
        assert "seed_user.py" not in image.steps()
        assert "Seed sentinel present" in result.stdout

    def test_skips_the_seed_without_an_email(self, image: _Image) -> None:
        """No ``SEED_USER_EMAIL``: no seed and no sentinel, and the deploy still passes."""
        result = self._deploy(image, OWNER_ROLE_PASSWORD=_password())

        assert result.returncode == 0, result.stderr
        assert image.steps()[-1] == "init_database.py"
        assert not image.sentinel().exists()

    @pytest.mark.parametrize(("failing", "ran"), [
        ("init_db_role.sql", ["pg_isready", "init_db.sql", "init_db_role.sql"]),
        ("init_database.py", ["pg_isready", "init_db.sql", "init_db_role.sql",
                              "init_database.py"]),
        ("seed_user.py", ["pg_isready", "init_db.sql", "init_db_role.sql",
                          "init_database.py", "seed_user.py"]),
    ])
    def test_a_failed_step_stops_the_deploy(
        self, image: _Image, failing: str, ran: list[str],
    ) -> None:
        """A step that fails ends the deploy non-zero with its troubleshooting report: no
        later step runs and no sentinel is written, so the web server does not start."""
        result = self._deploy(image, OWNER_ROLE_PASSWORD=_password(),
                              SEED_USER_EMAIL="owner@example.test", STUB_FAIL=failing)

        assert result.returncode != 0
        assert image.steps() == ran
        assert "Shekel deploy failed" in result.stdout
        assert not image.sentinel().exists()

    @pytest.mark.parametrize(("with_password", "flask_env"), [
        (True, "production"),
        (False, "deploy"),
    ])
    def test_refuses_to_run_outside_the_owners_entrypoint(
        self, image: _Image, with_password: bool, flask_env: str,
    ) -> None:
        """Run directly, without the owner's password or the deploy's configuration the
        owner's entrypoint sets, it stops by name before any step."""
        env = {"FLASK_ENV": flask_env}
        if with_password:
            env["OWNER_ROLE_PASSWORD"] = _password()

        result = image.run(DEPLOY, env=env)

        assert result.returncode == 1
        assert "scripts/deploy.sh runs under scripts/owner_entrypoint.sh" in result.stderr
        assert image.calls() == []


class TestRoleGrantsMakeNoLogin:
    """``scripts/init_db_role.sql`` grants; the logins and their passwords are made in the
    database container alone (``deploy/postgres/provision_roles.sh``, ruling plan#3413)."""

    @pytest.mark.parametrize("pattern", [
        r"\bCREATE\s+ROLE\b", r"\bALTER\s+ROLE\b", r"\bPASSWORD\b", r"\\getenv",
        r":'\w+'",
    ])
    def test_sets_no_password_and_makes_no_login(self, pattern: str) -> None:
        """No statement of the file (its comments aside) makes a login, sets a password or
        reads one from psql's variables."""
        statements = re.sub(r"--[^\n]*", "", ROLE_GRANTS.read_text(encoding="utf-8"))
        assert not re.search(pattern, statements, re.IGNORECASE), (
            f"scripts/init_db_role.sql matches {pattern!r}: a login and its password are "
            "made by deploy/postgres/provision_roles.sh alone"
        )
