class TestLibraryIsTheOneHome:
    """Each shared function is defined in the library and in none of the scripts."""

    @pytest.mark.parametrize("function", ["_load_secret", "_database_url",
                                          "_wait_for_postgres"])
    def test_defined_in_the_library_alone(self, function: str) -> None:
        """``function() {`` opens a line of the library and of no script that sources it."""
        definition = re.compile(rf"^{function}\(\)\s*\{{", re.MULTILINE)
        assert definition.search(_text(LIBRARY)), (
            f"{LIBRARY} no longer defines {function}"
        )
        for script in (WEB_ENTRYPOINT, OWNER_ENTRYPOINT, DEPLOY):
            assert not definition.search(_text(script)), (
                f"{script} defines its own {function}: the entrypoints share one, "
                f"in {LIBRARY}"
            )

    def test_each_script_sources_the_library(self) -> None:
        """All three scripts source it from beside themselves, as the image lays them out."""
        for script, path in ((WEB_ENTRYPOINT, "/scripts/_entrypoint_lib.sh"),
                             (OWNER_ENTRYPOINT, "/_entrypoint_lib.sh"),
                             (DEPLOY, "/_entrypoint_lib.sh")):
            assert f'source "$(dirname "${{BASH_SOURCE[0]}}"){path}"' in _text(script), (
                f"{script} does not source {LIBRARY} from beside itself"
            )

    def test_the_library_loads_no_secret_itself(self) -> None:
        """Sourcing the library loads nothing, so each entrypoint's list is all it loads."""
        assert _loaded(LIBRARY) == set()

    def test_the_container_runs_scripts_that_are_executable(self) -> None:
        """The image's ENTRYPOINT and the migrate service's entrypoint and command are run
        directly, so each is executable as committed; the library is sourced, not run."""
        for script in (WEB_ENTRYPOINT, OWNER_ENTRYPOINT, DEPLOY):
            assert (REPO_ROOT / script).stat().st_mode & stat.S_IXUSR, (
                f"{script} is not executable; a container that runs it refuses to start"
            )


class TestLoaderBehaviour:
    """``_load_secret`` against real files: it loads a present one, falls back silently to the
    variable when the file is absent, refuses an empty one, and drops only a trailing newline."""

    def test_loader_reads_secret_when_file_present(self, image: _Image) -> None:
        """A populated file overrides any env value the helper sees."""
        image.secret("secret_key", "a" * SECRET_KEY_HEX_BYTES)

        result = image.bash(
            # Pre-set the env var to a known wrong value so we can prove the loader
            # OVERWROTE it (not merely appended to a missing var).
            "export TEST_SECRET_KEY=stale-env-value\n"
            "_load_secret TEST_SECRET_KEY secret_key\n"
            "echo \"VAR=${TEST_SECRET_KEY}\""
        )

        assert result.returncode == 0, (
            f"loader exited non-zero: stderr={result.stderr!r}"
        )
        # Exact match: 64 ``a`` characters, no trailing whitespace.
        assert f"VAR={'a' * SECRET_KEY_HEX_BYTES}\n" in result.stdout, (
            f"loader did not overwrite env var with file content; "
            f"stdout={result.stdout!r}"
        )

    def test_loader_falls_back_to_env_when_file_absent(self, image: _Image) -> None:
        """A missing file is a silent no-op; env value is preserved."""
        result = image.bash(
            "export TEST_SECRET=fallback-env-value\n"
            # The argument 'nonexistent_file' has no matching file in the secrets folder,
            # so the loader returns 0 without touching the var.
            "_load_secret TEST_SECRET nonexistent_file\n"
            "echo \"VAR=${TEST_SECRET}\""
        )

        assert result.returncode == 0, (
            f"loader exited non-zero on missing file: stderr={result.stderr!r}"
        )
        assert "VAR=fallback-env-value" in result.stdout, (
            "loader mutated the env var when the secret file was "
            f"absent; stdout={result.stdout!r}"
        )
        # No "Loaded ..." log line should fire when the file is absent.
        assert "Loaded " not in result.stdout, (
            "loader logged a ``Loaded ...`` line for a missing file; "
            "the no-op branch should be silent."
        )

    def test_loader_rejects_empty_secret_file(self, image: _Image) -> None:
        """A present-but-empty file is a misconfiguration -- fail fast."""
        image.secret("empty_file", "")

        result = image.bash("_load_secret TEST_SECRET empty_file")

        assert result.returncode != 0, (
            "loader accepted an empty secret file and would have "
            "exported an empty value -- the operator's intent to use "
            "file-backed secrets is clear (file exists) but the file "
            "is empty; this is a misconfiguration that must fail fast."
        )
        assert "is present but empty" in result.stderr, (
            f"loader did not emit the expected diagnostic for an empty "
            f"secret file; stderr={result.stderr!r}"
        )

    def test_loader_strips_trailing_newline(self, image: _Image) -> None:
        """``echo "value" > file`` writes a trailing newline; loader strips it.

        Bash's ``$(< file)`` command substitution strips trailing newlines, so a file
        written by the typical ``echo`` pattern produces the same in-process value as
        ``printf 'value' > file``.  This is the load-bearing reason the helper uses
        ``$(< ...)`` instead of ``cat``.
        """
        image.secret("with_newline", "value-with-trailing-newline\n")

        result = image.bash(
            "_load_secret TEST_VAR with_newline\n"
            # ``${#TEST_VAR}`` is the byte length, asserted directly so a regression that
            # leaves the newline in surfaces as a precise number.
            "echo \"LEN=${#TEST_VAR}\"\n"
            "echo \"VAL=${TEST_VAR}\""
        )

        assert result.returncode == 0, result.stderr
        # 27 = len("value-with-trailing-newline").
        assert "LEN=27" in result.stdout, (
            f"loader did not strip the trailing newline; stdout={result.stdout!r}"
        )
        assert "VAL=value-with-trailing-newline" in result.stdout

    def test_loader_preserves_special_characters(self, image: _Image) -> None:
        """Special characters (URL-safe base64, punctuation) survive the load.

        Fernet keys are URL-safe base64 (``A-Za-z0-9_-=``).  TOTP encryption keys generated
        by ``Fernet.generate_key()`` end with ``=`` padding which a sloppy shell
        substitution (``eval``, double-quoted ``$VAR`` in the wrong context) could mangle.
        Random bash special chars (``$``, `` ``, ``"``) are tested so a future use of
        ``$()`` or unquoted variable expansion in the helper surfaces here.
        """
        special = "k_AbC123-_=+/!@#$%^&*() with spaces and \"quotes\""
        image.secret("special_secret", special)

        # The loaded value is base64-encoded to assert on it without going through any
        # further shell quoting.
        result = image.bash(
            "_load_secret TEST_VAR special_secret\n"
            "printf '%s' \"$TEST_VAR\" | base64 -w0\n"
            "echo \"\""
        )

        assert result.returncode == 0, result.stderr
        expected_b64 = base64.b64encode(special.encode("utf-8")).decode("ascii")
        assert expected_b64 in result.stdout, (
            f"loader mangled special characters; expected b64="
            f"{expected_b64!r}, got stdout={result.stdout!r}"
        )


