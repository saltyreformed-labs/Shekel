"""The app image's entrypoints and the deploy (card plan#2166; rulings plan#3412, plan#3413).

``entrypoint.sh`` is the web server's, ``scripts/owner_entrypoint.sh`` the migrate service's,
``scripts/deploy.sh`` that service's command, and ``scripts/_entrypoint_lib.sh`` what all three
source: the secret loader (audit finding F-148 / Commit C-38), the database URL and the wait for
PostgreSQL.

Each script is run as bash runs it in the container, from a copy of the four laid out as the
image lays them out, in the test's own folder.  The copy reads its secrets from a folder of the
test's instead of ``/run/secrets`` and writes the seed sentinel under one instead of
``/home/shekel/app/state``: those two paths are rewritten in the copy, and nothing else.  The
commands the scripts run against a database -- ``pg_isready``, ``psql`` and ``python`` -- are
stubs first on ``PATH`` that record their arguments and their whole environment, so a test reads
what each was handed and in what order; ``record`` is one more, a command that records the
environment it was started with.  Each run's environment holds only what its test gives it.

The source-shape tests beside the runs pin what a run cannot show: which secrets each entrypoint
loads, and that the web server's names no owner or superuser credential at all.
"""
from __future__ import annotations

import base64
import json
import re
import secrets
import stat
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]

# ── Files under assertion ──────────────────────────────────────────
WEB_ENTRYPOINT = "entrypoint.sh"
LIBRARY = "scripts/_entrypoint_lib.sh"
OWNER_ENTRYPOINT = "scripts/owner_entrypoint.sh"
DEPLOY = "scripts/deploy.sh"
ROLE_GRANTS = REPO_ROOT / "scripts" / "init_db_role.sql"
_SCRIPTS = (WEB_ENTRYPOINT, LIBRARY, OWNER_ENTRYPOINT, DEPLOY)

#: The two paths a copy reads and writes outside itself, rewritten into the test's folder.
_SECRETS_PATH = "/run/secrets/"
_STATE_PATH = "/home/shekel/app/state"

#: The commands the stubs stand in for, and the one that records its environment.
_STUBBED = ("pg_isready", "psql", "python", "record")
#: Each stub records its name, its arguments and its environment, one JSON line per call, and
#: exits 1 when ``STUB_FAIL`` names the last path component of one of its arguments.
_STUB_SOURCE = """\
import json, os, sys
name, args = os.path.basename(sys.argv[0]), sys.argv[1:]
with open(os.environ["STUB_LOG"], "a", encoding="utf-8") as log:
    log.write(json.dumps({"command": name, "args": args, "env": dict(os.environ)}) + "\\n")
if os.environ.get("STUB_FAIL") in {os.path.basename(arg) for arg in args}:
    sys.exit(1)
"""

#: The secrets the web server's entrypoint loads, and the owner's entrypoint's one.
_WEB_SECRETS = {
    ("SECRET_KEY", "secret_key"),
    ("APP_ROLE_PASSWORD", "app_role_password"),
    ("TOTP_ENCRYPTION_KEY", "totp_encryption_key"),
    ("TOTP_ENCRYPTION_KEY_OLD", "totp_encryption_key_old"),
    ("VALKEY_PASSWORD", "valkey_password"),
}
_OWNER_SECRETS = {("OWNER_ROLE_PASSWORD", "owner_role_password")}

#: Length of a SECRET_KEY generated by ``token_hex(32)`` -- the documented production form.
SECRET_KEY_HEX_BYTES = 64
#: Subprocess timeout for one run of a script.  Each does no I/O beyond its copy's files and
#: its stubs; 10 s is generous.
_RUN_TIMEOUT_S = 10

_LOAD_CALL = re.compile(r"^\s*_load_secret\s+(\w+)\s+(\w+)\s*$", re.MULTILINE)


def _text(relative: str) -> str:
    """The committed source of ``relative``."""
    return (REPO_ROOT / relative).read_text(encoding="utf-8")


def _loaded(relative: str) -> set[tuple[str, str]]:
    """The ``(variable, secret file)`` pairs ``relative`` calls ``_load_secret`` with."""
    return set(_LOAD_CALL.findall(_text(relative)))


def _password() -> str:
    """A login password of the kind the provisioning script accepts."""
    return secrets.token_urlsafe(24)


def _url(role: str, password: str, *, host: str = "db", query: str = "") -> str:
    """The URL the library builds for ``role`` on the default port and database."""
    return f"postgresql://{role}:{password}@{host}:5432/shekel{query}"


@dataclass(frozen=True)
class _Image:
    """A copy of the four scripts as the image lays them out, and its stubs."""

    root: Path
    secrets_dir: Path
    state_dir: Path
    bin_dir: Path
    log: Path

    def run(self, script: str, *command: str,
            env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
        """Run the copy's ``script`` with ``command`` as its arguments, in an environment
        holding only ``env``, the stubs' ``PATH`` and their log."""
        environment = {"PATH": f"{self.bin_dir}:/usr/bin:/bin", "STUB_LOG": str(self.log),
                       **(env or {})}
        return subprocess.run(["bash", str(self.root / script), *command], env=environment,
                              capture_output=True, text=True, timeout=_RUN_TIMEOUT_S,
                              check=False)

    def bash(self, body: str, env: dict[str, str] | None = None
             ) -> subprocess.CompletedProcess[str]:
        """Run ``body`` in bash after sourcing the copy's library, as the scripts do."""
        script = f"set -eEo pipefail\nsource {self.root / LIBRARY}\n{body}\n"
        return subprocess.run(["bash", "-c", script],
                              env={"PATH": "/usr/bin:/bin", **(env or {})},
                              capture_output=True, text=True, timeout=_RUN_TIMEOUT_S,
                              check=False)

    def secret(self, name: str, value: str) -> None:
        """Mount ``value`` as the secret file ``name``."""
        (self.secrets_dir / name).write_text(value, encoding="utf-8")

    def calls(self) -> list[dict[str, object]]:
        """Every stub's record, in the order they ran."""
        if not self.log.exists():
            return []
        return [json.loads(line) for line in self.log.read_text(encoding="utf-8").splitlines()]

    def steps(self) -> list[str]:
        """Each database command run, named by what it ran: ``pg_isready``, the file ``psql``
        was given, the script ``python`` was; the ``record`` command as ``record``."""
        named = []
        for call in self.calls():
            args = call["args"]
            if call["command"] == "psql":
                named.append(Path(args[args.index("-f") + 1]).name)
            elif call["command"] == "python":
                named.append(Path(args[0]).name)
            else:
                named.append(call["command"])
        return named

    def sentinel(self) -> Path:
        """Where the copy's deploy writes the seed sentinel."""
        return self.state_dir / ".seed-complete"


@pytest.fixture(name="image")
def _image_fixture(tmp_path: Path) -> _Image:
    """The four scripts copied into ``tmp_path`` as the image lays them out, their two outside
    paths moved into it, with the stubs."""
    root, secrets_dir = tmp_path / "app", tmp_path / "secrets"
    state_dir, bin_dir = tmp_path / "state", tmp_path / "bin"
    secrets_dir.mkdir()
    bin_dir.mkdir()
    for relative in _SCRIPTS:
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(_text(relative).replace(_SECRETS_PATH, f"{secrets_dir}/")
                          .replace(_STATE_PATH, str(state_dir)), encoding="utf-8")
        target.chmod(stat.S_IMODE((REPO_ROOT / relative).stat().st_mode))
    for name in _STUBBED:
        stub = bin_dir / name
        stub.write_text(f"#!{sys.executable}\n{_STUB_SOURCE}", encoding="utf-8")
        stub.chmod(0o755)
    return _Image(root, secrets_dir, state_dir, bin_dir, tmp_path / "stub_calls.jsonl")


