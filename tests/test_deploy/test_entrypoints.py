class TestWebEntrypointSource:
    """What the web server's entrypoint loads, checks and never names."""

    def test_loads_the_web_servers_secrets_and_no_other(self) -> None:
        """Exactly the web server's five, each from its own file: no superuser or owner
        password among them (ruling plan#3412)."""
        assert _loaded(WEB_ENTRYPOINT) == _WEB_SECRETS

    def test_loader_invocations_precede_secret_key_validation(self) -> None:
        """Every ``_load_secret`` call appears BEFORE the SECRET_KEY shape check.

        Ordering invariant: the SECRET_KEY length / placeholder check only works if the env
        var is already populated from whichever source (file or env).  A loader run AFTER the
        validation would let a placeholder pass the check and then have its real value
        loaded, so the value the server uses would never be inspected.
        """
        text = _text(WEB_ENTRYPOINT)
        loader_calls = list(_LOAD_CALL.finditer(text))
        assert loader_calls, "no _load_secret invocations found"
        # ``:-`` tolerated: nounset (polyglot audit OPS/SH-23) references the variable as
        # ${SECRET_KEY:-} so the crafted diagnostic fires instead of a bare unbound-variable.
        validation_match = re.search(r'\[\s*-z\s+"\$\{SECRET_KEY(?::-)?\}"\s*\]', text)
        assert validation_match is not None, (
            "entrypoint.sh no longer validates SECRET_KEY shape"
        )
        assert max(m.start() for m in loader_calls) < validation_match.start(), (
            "_load_secret invocation appears AFTER the SECRET_KEY "
            "shape check; the validation runs against the env-only "
            "value and the file-backed override would slip past it."
        )

    def test_secret_key_placeholder_rejected_at_entrypoint(self) -> None:
        """``replaced_by_docker_secret*`` is among the SECRET_KEY case statement's patterns.

        The placeholder is the documented form an operator leaves in .env when migrating to
        Posture 2 (file-backed secrets).  If /run/secrets/secret_key is missing or
        unreadable, the placeholder remains as the active SECRET_KEY -- a publicly-known
        value.
        """
        assert re.search(r"replaced_by_docker_secret\*", _text(WEB_ENTRYPOINT)), (
            "entrypoint.sh case statement does not reject the "
            "``replaced_by_docker_secret*`` placeholder; an operator "
            "whose docker secret file is missing would silently boot "
            "under the public placeholder value (audit finding F-148 "
            "regression / hole in Commit C-38)."
        )

    @pytest.mark.parametrize("name", [
        "POSTGRES_PASSWORD", "postgres_password", "DB_PASSWORD", "DB_USER",
        "DATABASE_URL", "PGPASSWORD", "OWNER_ROLE_PASSWORD", "owner_role_password",
        "shekel_owner", "shekel_user",
    ])
    def test_names_no_owner_or_superuser_credential(self, name: str) -> None:
        """No superuser or owner credential, nor the variables that carried one, is named
        anywhere in the web server's entrypoint, so gunicorn inherits none from it.
        (``DATABASE_URL_APP``, the web login's URL, is a different name.)"""
        assert not re.search(rf"\b{name}\b", _text(WEB_ENTRYPOINT)), (
            f"entrypoint.sh names {name}: the web server holds no owner or superuser "
            "credential (card plan#2166)"
        )

    @pytest.mark.parametrize("name", [
        r"psql", r"init_db\.sql", r"init_db_role\.sql", r"init_database\.py",
        r"seed_user\.py", r"SEED_USER_\w*",
    ])
    def test_does_no_deploy_work(self, name: str) -> None:
        """The deploy's steps, and the seed's credentials, are the migrate service's alone:
        none is named in the web server's entrypoint."""
        assert not re.search(rf"\b{name}\b", _text(WEB_ENTRYPOINT)), (
            f"entrypoint.sh names {name}: the deploy runs in the migrate service "
            "(scripts/deploy.sh), and the web server reads no seed credential"
        )

    def test_entrypoint_rejects_placeholder_when_secret_file_missing(self) -> None:
        """The SECRET_KEY validation section, run with the docker-secret placeholder, exits
        non-zero with the placeholder diagnostic and the runbook hint.

        The whole 0a section is extracted (up to ``# ── 0b.``) because its case statement
        holds a nested case for the docker-secret hint; a capture to the first ``esac`` would
        truncate at the inner one.  The placeholder (32+ chars) clears the length check, so
        the case statement is what must catch it.
        """
        match = re.search(
            r"(# ── 0a\. Validate SECRET_KEY shape.*?)(?=\n# ── 0b\.)",
            _text(WEB_ENTRYPOINT),
            re.DOTALL,
        )
        if match is None:
            pytest.fail(
                "Could not extract SECRET_KEY validation section "
                "from entrypoint.sh; the section must start with "
                "``# ── 0a. Validate SECRET_KEY shape`` and end "
                "before ``# ── 0b.``."
            )
        script = (
            "#!/bin/bash\n"
            "set -eEo pipefail\n"
            'export SECRET_KEY="replaced_by_docker_secret_padded_to_be_long_enough"\n'
            f"{match.group(1)}\n"
            'echo "should-not-reach"\n'
        )
        result = subprocess.run(["bash", "-c", script], capture_output=True, text=True,
                                timeout=_RUN_TIMEOUT_S, check=False)
        assert result.returncode != 0, (
            "entrypoint.sh validation accepted "
            "``replaced_by_docker_secret_padded_...`` as a valid "
            "SECRET_KEY; the placeholder pattern is not in the "
            "rejected case branches."
        )
        assert "known placeholder" in result.stderr, (
            f"entrypoint.sh did not emit the ``known placeholder`` "
            f"diagnostic for the docker-secret placeholder; "
            f"stderr={result.stderr!r}"
        )
        assert "Migrating to Docker secrets" in result.stderr, (
            "entrypoint.sh placeholder rejection does not point the "
            "operator at the runbook section; the operator has no "
            "discoverable hint that the secret file is missing."
        )
        assert "should-not-reach" not in result.stdout


class TestWebEntrypointRun:
    """The web server's entrypoint, run: it waits for the database and hands its command the
    web login's URL, and touches the database no other way."""

    def _env(self, **extra: str) -> dict[str, str]:
        """A web container's environment: a valid secret key and app login password."""
        return {"SECRET_KEY": secrets.token_hex(32), "APP_ROLE_PASSWORD": _password(),
                **extra}

    def test_hands_the_server_the_web_logins_url_and_nothing_else_of_the_database(
        self, image: _Image,
    ) -> None:
        """Its command starts with ``DATABASE_URL_APP``, the web login's URL with the TLS
        mode; the only database command before it is the wait, as the web login; and the
        configuration the stack named is left as it was."""
        env = self._env(DB_HOST="database.internal", DB_SSLMODE="require",
                        FLASK_ENV="production")

        result = image.run(WEB_ENTRYPOINT, "record", env=env)

        assert result.returncode == 0, result.stderr
        assert image.steps() == ["pg_isready", "record"]
        wait, started = image.calls()
        assert wait["args"] == ["-h", "database.internal", "-p", "5432", "-U", "shekel_app",
                                "-q"]
        assert started["env"]["DATABASE_URL_APP"] == _url(
            "shekel_app", env["APP_ROLE_PASSWORD"], host="database.internal",
            query="?sslmode=require")
        assert started["env"]["FLASK_ENV"] == "production"

    def test_a_mounted_app_password_file_wins_over_the_variable(self, image: _Image) -> None:
        """The web login's URL carries the mounted file's password, not the variable's."""
        mounted = _password()
        image.secret("app_role_password", f"{mounted}\n")

        result = image.run(WEB_ENTRYPOINT, "record", env=self._env())

        assert result.returncode == 0, result.stderr
        assert image.calls()[-1]["env"]["DATABASE_URL_APP"] == _url("shekel_app", mounted)


