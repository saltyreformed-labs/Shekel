FROZEN_TODAY = date(2026, 6, 15)
_FUTURE_START = date(2026, 7, 3)  # first payday after the frozen today

#: ``seed_user``'s 2024 bootstrap paycheck counts toward the rolling target,
#: and since plan step **C3-b** it always will.  Its stored end was
#: 2024-01-18 -- long past ``FROZEN_TODAY``, so ``_future_period_count``
#: skipped it -- but the writer now materialises the payday derivation, in
#: which a period ends the day before the NEXT payday.  With the next payday
#: at 2026-07-03 the bootstrap covers 2024-01-05..2026-07-02, which CONTAINS
#: the frozen today, so it is the current period rather than a historical one.
#: That is ledger row **P27**'s absorption working as ruled, on the fixture
#: this suite happens to build; the deficit arithmetic below counts it.
_BOOTSTRAP_IN_WINDOW = 1


@pytest.fixture(autouse=True)
def _freeze(monkeypatch):
    """Pin ``date.today()`` so "current vs future" is deterministic."""
    freeze_today(monkeypatch, FROZEN_TODAY)


def _last_covered_day(user_id, period_id):
    """Return a period's last covered day, DERIVED.

    ``period.end_date`` until plan step ``pay_calendar:C4-c`` dropped the
    column; a period runs to the day before the next payday, which is a
    property of the owner's whole payday set rather than of one row.
    """
    return calendar_for(user_id).period_by_id(period_id).end_date


def _future_periods(db_session, seed_user, count, start=_FUTURE_START):
    """Generate `count` biweekly future periods (indices 1..count)."""
    periods = record_paydays_across_a_hole(
        user_id=seed_user["user"].id,
        first_payday=start,
        num_periods=count,
        rhythm=rhythm_of(14),
    )
    db_session.commit()
    return periods


def _enable_rolling(db_session, user_id, target):
    """Turn rolling on at ``target`` for an owner who already holds an era.

    The rhythm is not restated here: every caller recorded its paydays
    through ``record_paydays`` first, which minted the era the top-up under
    test continues (plan step ``pay_calendar:C17-a``), and rolling is the
    schedule row's own fact with its own door.
    """
    pay_schedule_service.set_rolling(user_id, enabled=True, target_periods=target)
    db_session.commit()


def _count_periods(db_session, user_id):
    """Total pay periods owned by the user."""
    return db_session.query(PayPeriod).filter_by(user_id=user_id).count()


def _future_count(user_id):
    """How many paychecks have not ENDED before ``FROZEN_TODAY``.

    The rolling target's own question, asked of the derived calendar
    (:meth:`~app.services.pay_calendar.PayCalendar.current_and_future`).  It
    counted ``PayPeriod.end_date >= FROZEN_TODAY`` in SQL until plan step
    ``pay_calendar:C4-c`` dropped that column; the derivation is where the end
    lives, and it is what the door under test reads.
    """
    return len(calendar_for(user_id).current_and_future(FROZEN_TODAY).periods)


def _top_up_and_populate(user_id):
    """Run BOTH halves of a rolling top-up, exactly as ``/grid`` does.

    ``top_up_rolling_window`` appends the deficit and leaves the new paydays
    EMPTY; ``populate_new_periods`` opens the generate pass afterwards and
    fills them.  Ruling **R-R38**: the pass may only be opened above the
    service layer, and only after the write.

    Args:
        user_id: The owning user's id.

    Returns:
        The newly appended periods, now populated (empty when the window was
        already full).
    """
    new_periods = pay_period_rolling.top_up_rolling_window(user_id)
    populate_new_periods(user_id, new_periods)
    return new_periods


class TestTopUpFastPaths:
    """The cheap paths: no write work, and the service takes no lock.

    **What "no lock" means changed at plan step ``balance:X-bn``.**  The
    service takes no lock on ANY path now (ruling **R-CC115**), so each "no
    lock" below is a regression pin for an acquisition re-added inside it
    (measured 2026-09-29: one re-added at the top-up's top turns all three
    red).  It is NOT a claim about the page: ``/grid``'s and ``/dashboard``'s
    ``write_transaction`` block is a command transaction and takes the
    owner's write lock at its first statement whether or not rolling is on
    (ruling **R-CC114**), which plan step ``balance:X-cz`` (a page load never
    writes) removes.  *Until that step these grades said the page's fast
    paths took no lock.*
    """

    def test_no_schedule_row_returns_zero_no_lock(self, app, db, seed_user):
        """A user with no schedule row is a no-op, and the service takes no lock."""
        with app.app_context():
            _future_periods(db.session, seed_user, count=3)
            before = _count_periods(db.session, seed_user["user"].id)
            result, statements = capture_sql_statements(
                lambda: pay_period_rolling.top_up_rolling_window(
                    seed_user["user"].id,
                )
            )
            assert result == []
            assert not took_advisory_lock(statements)
            assert _count_periods(db.session, seed_user["user"].id) == before

    def test_disabled_returns_zero_no_lock(self, app, db, seed_user):
        """Rolling disabled -> 0, no write, and the service takes no lock."""
        user_id = seed_user["user"].id
        with app.app_context():
            _future_periods(db.session, seed_user, count=3)
            # Row exists (the batch above created it) and rolling is off,
            # the column default.
            db.session.commit()
            before = _count_periods(db.session, user_id)
            result, statements = capture_sql_statements(
                lambda: pay_period_rolling.top_up_rolling_window(user_id)
            )
            assert result == []
            assert not took_advisory_lock(statements)
            assert _count_periods(db.session, user_id) == before

    def test_full_window_returns_zero_no_lock(self, app, db, seed_user):
        """future_count >= target returns 0; nothing created, no lock taken here."""
        user_id = seed_user["user"].id
        with app.app_context():
            _future_periods(db.session, seed_user, count=3)  # 3 future
            _enable_rolling(db.session, user_id, target=3)
            before = _count_periods(db.session, user_id)
            result, statements = capture_sql_statements(
                lambda: pay_period_rolling.top_up_rolling_window(user_id)
            )
            assert result == []
            assert not took_advisory_lock(statements)
            assert _count_periods(db.session, user_id) == before

    def test_current_period_counts_toward_target(self, app, db, seed_user):
        """The period containing today counts as one of the N kept ahead.

        With exactly one period spanning the frozen today (so
        ``end_date >= today``) and a target of 1, the window is already
        satisfied and the top-up creates nothing -- proof that "keep N
        ahead" counts the current period, not only strictly-future ones.
        """
        user_id = seed_user["user"].id
        with app.app_context():
            # 06-08..06-21 contains the frozen today (06-15).
            record_paydays_across_a_hole(
                user_id=user_id, first_payday=date(2026, 6, 8),
                num_periods=1, rhythm=rhythm_of(14),
            )
            db.session.commit()
            _enable_rolling(db.session, user_id, target=1)
            before = _count_periods(db.session, user_id)
            assert pay_period_rolling.top_up_rolling_window(user_id) == []
            assert _count_periods(db.session, user_id) == before


class TestTopUpDeficitPath:
    """The deficit path creates exactly the shortfall, idempotently."""

    def test_deficit_creates_exactly_deficit_and_takes_no_lock_itself(
        self, app, db, seed_user,
    ):
        """A deficit of D creates exactly D periods, and the service takes no lock.

        Since plan step ``balance:X-bn`` (ruling **R-CC115**) the lock is the
        REQUEST's: ``/grid``'s ``write_transaction`` block takes it where its
        command transaction begins, graded below.  Called directly, outside a
        request, the top-up takes none, which is the regression pin for an
        acquisition re-added inside it (measured 2026-09-29: one re-added at
        its top turns this red).  *Until that step this asserted the service
        took the lock on a deficit.*
        """
        user_id = seed_user["user"].id
        with app.app_context():
            _future_periods(db.session, seed_user, count=3)  # idx 1..3 future
            _enable_rolling(db.session, user_id, target=5)
            result, statements = capture_sql_statements(
                lambda: pay_period_rolling.top_up_rolling_window(user_id)
            )
            db.session.commit()

            # 5 target - (3 future + the absorbed bootstrap, now current).
            assert len(result) == 5 - (3 + _BOOTSTRAP_IN_WINDOW)
            assert not took_advisory_lock(statements)
            # The window now holds exactly the target.
            assert _future_count(user_id) == 5
            # Disciplines 1 + 3.
            assert_pay_period_invariants(db.session, user_id)
            assert all(r.passed for r in check_balance_anomalies(db.session))
            assert all(r.passed for r in check_referential_integrity(db.session))

    def test_a_grid_deficit_is_counted_and_appended_under_the_owner_s_lock(
        self, app, db, auth_client, seed_user,
    ):
        """Through ``GET /grid``: the block's lock precedes the count and the append.

        The top-up counts the owner's paychecks and appends against that
        count, so a count read before the lock lets two tabs both append.
        The block's command transaction takes the owner's key at its first
        statement, so every read and INSERT of the top-up follows it; the
        deficit is asserted to have been appended, so the order cannot pass
        over a render that appended nothing.
        """
        user_id = seed_user["user"].id
        with app.app_context():
            _future_periods(db.session, seed_user, count=3)
            _enable_rolling(db.session, user_id, target=5)

        response, statements = capture_sql_statements(
            lambda: auth_client.get("/grid"),
        )

        assert response.status_code == 200
        keys = advisory_lock_keys(statements)
        assert keys == [owner_lock_key(user_id)], keys
        lock_at = next(
            i for i, (sql, _params) in enumerate(statements)
            if "pg_advisory_xact_lock" in sql
        )
        inserts = [
            i for i, (sql, _params) in enumerate(statements)
            if sql.lstrip().upper().startswith("INSERT INTO BUDGET.PAY_PERIODS")
        ]
        # ONE append statement: SQLAlchemy sends a multi-period append as one
        # multi-row INSERT, so the NUMBER appended is graded by the window
        # below, not by counting statements.
        assert len(inserts) == 1, inserts
        assert lock_at < inserts[0]
        schedule_reads = [
            i for i, (sql, _params) in enumerate(statements)
            if "budget.pay_schedule " in sql and i > lock_at
        ]
        assert schedule_reads and schedule_reads[0] < inserts[0], (
            "the top-up read no schedule under the lock before appending"
        )
        count_reads = [
            i for i, (sql, _params) in enumerate(statements)
            if "FROM budget.pay_periods" in sql and lock_at < i < inserts[0]
        ]
        assert count_reads, (
            "the top-up counted no paychecks under the lock before appending"
        )
        with app.app_context():
            assert _future_count(user_id) == 5

    def test_second_call_is_idempotent_noop(self, app, db, seed_user):
        """Once the window is full, a second top-up creates nothing."""
        user_id = seed_user["user"].id
        with app.app_context():
            _future_periods(db.session, seed_user, count=3)
            _enable_rolling(db.session, user_id, target=5)
            first = pay_period_rolling.top_up_rolling_window(user_id)
            db.session.commit()
            second = pay_period_rolling.top_up_rolling_window(user_id)
            db.session.commit()
            assert len(first) == 5 - (3 + _BOOTSTRAP_IN_WINDOW)
            assert second == []
            assert _future_count(user_id) == 5
            assert_pay_period_invariants(db.session, user_id)

    def test_the_topped_up_paydays_extend_the_owners_own_rhythm(
        self, app, db, seed_user,
    ):
        """The appended paydays continue the schedule at its stored cadence.

        **This asserted a contiguous ``period_index`` sequence until plan step
        ``pay_calendar:C4-c``**, which is a property nothing can now violate:
        the ordinal is a row's position in payday order, so it runs 0..n-1 by
        construction and a duplicate is not expressible.  What a top-up can
        still get wrong is the DAY it appends -- the whole point of the door is
        to extend the owner's rhythm rather than to invent one -- so that is
        what this asserts instead.
        """
        user_id = seed_user["user"].id
        with app.app_context():
            _future_periods(db.session, seed_user, count=2)
            _enable_rolling(db.session, user_id, target=6)
            pay_period_rolling.top_up_rolling_window(user_id)
            db.session.commit()

            paydays = [period.start_date for period in all_periods(user_id)]
            # bootstrap + the 2 seeded + the 3 topped up.  The bootstrap counts
            # toward the target of 6, so the deficit is 3 rather than 4.
            assert len(paydays) == 6
            assert paydays == sorted(paydays)
            gaps = {
                (later - earlier).days
                for earlier, later in zip(paydays[1:], paydays[2:])
            }
            assert gaps == {SEED_USER_CADENCE_DAYS}, (
                f"the top-up appended paydays {gaps} days apart; the owner's "
                f"stored cadence is {SEED_USER_CADENCE_DAYS}"
            )

    def test_the_top_up_leaves_the_new_periods_EMPTY(
        self, app, db, seed_user,
    ):
        """The top-up appends and generates nothing into what it appended.

        The door's half of ruling **R-R38**.  The case below runs both halves
        over the same fixture and finds a row in every appended period, so
        this one cannot pass by the template being unable to generate.
        """
        user_id = seed_user["user"].id
        with app.app_context():
            _future_periods(db.session, seed_user, count=2)
            make_expense_template(db.session, seed_user, amount="1200.00")
            db.session.commit()
            _enable_rolling(db.session, user_id, target=5)
            created = pay_period_rolling.top_up_rolling_window(user_id)
            db.session.commit()
            assert len(created) == 5 - (2 + _BOOTSTRAP_IN_WINDOW)
            for period in created:
                assert (
                    db.session.query(Transaction)
                    .filter_by(pay_period_id=period.id)
                    .count()
                ) == 0, (
                    "the top-up generated a recurring row; since R-R38 the "
                    "read pass one is resolved in is opened by the route"
                )

    def test_new_periods_get_recurring_rows(self, app, db, seed_user):
        """Top-up + populate fills the appended periods from the templates."""
        user_id = seed_user["user"].id
        with app.app_context():
            _future_periods(db.session, seed_user, count=2)
            make_expense_template(db.session, seed_user, amount="1200.00")
            db.session.commit()
            _enable_rolling(db.session, user_id, target=5)
            new_periods = _top_up_and_populate(user_id)
            db.session.commit()
            assert len(new_periods) == 5 - (2 + _BOOTSTRAP_IN_WINDOW)
            for period in new_periods:
                txns = (
                    db.session.query(Transaction)
                    .filter_by(pay_period_id=period.id)
                    .all()
                )
                assert len(txns) == 1
                assert resolved_amount(txns[0]) == Decimal("1200.00")

    def test_balances_correct_after_topup(self, app, db, seed_user):
        """Discipline 2: as-of balances continue correctly into the new window.

        Anchor $1000 at index 0 (no expense).  A $1200 every-period expense
        fills indices 1..3, so the projected end balance at index N is
        1000 - N*1200.  Rolling target 5 tops up index 4 with the same
        expense, so the projection continues to 1000 - 4*1200 in the new
        window while the retained window is untouched.

        **The deficit is ONE, not two, and plan step C3-b is why**: the
        absorbed bootstrap paycheck now contains ``FROZEN_TODAY`` and counts
        toward the target (see :data:`_BOOTSTRAP_IN_WINDOW`).  The figures
        move with it -- the point of this test is that the projection
        CONTINUES through the top-up, not how many periods it added.
        """
        account = seed_user["account"]
        scen = seed_user["scenario"].id
        user_id = seed_user["user"].id
        with app.app_context():
            periods = _future_periods(db.session, seed_user, count=3)  # idx 1..3
            make_expense_template(db.session, seed_user, amount="1200.00")
            populate_in_a_fresh_pass(user_id, {p.id for p in periods})
            db.session.commit()

            # Retained window before the top-up: 1000 - 2*1200 at index 2.
            # The period's last covered day is the calendar's since plan step
            # ``pay_calendar:C4-c`` dropped ``pay_periods.end_date``.
            retained_end = _last_covered_day(user_id, periods[1].id)
            retained = seam_cash_balance_at(account, scen, retained_end)
            assert retained == Decimal("-1400.00")

            _enable_rolling(db.session, user_id, target=5)
            created = _top_up_and_populate(user_id)
            db.session.commit()
            assert len(created) == 5 - (3 + _BOOTSTRAP_IN_WINDOW)

            # New window: the projection continues to 1000 - 4*1200.
            new_last = all_periods(user_id)[-1]  # idx 4
            assert seam_cash_balance_at(
                account, scen, _last_covered_day(user_id, new_last.id),
            ) == Decimal("-3800.00")
            # Retained window untouched -- and its end has not moved either,
            # which the re-derivation is what makes worth asserting.
            assert _last_covered_day(user_id, periods[1].id) == retained_end
            assert seam_cash_balance_at(
                account, scen, retained_end,
            ) == retained

            assert_pay_period_invariants(db.session, user_id)
            assert all(r.passed for r in check_balance_anomalies(db.session))
            assert all(r.passed for r in check_referential_integrity(db.session))


class TestTheTopUpCountsOnTheOwnersDay:
    """"How many paychecks are left" is asked of the OWNER's clock.

    Plan step **C2-f3b**, ruled 2026-08-19 with the lock classifier's -- finding
    **balance:N-191** named this door as the second of the two sites deciding
    something against the user's CALENDAR on ``date.today()``.  Both live callers
    (``/grid`` and ``/dashboard``) pass no ``as_of``, so the default IS the
    decision, and an adversarial review of this step found it ungraded.

    Where the clocks differ the owner's day is the EARLIER one, so a period the
    process clock has already retired still counts as future -- the window looks
    one paycheck longer and the top-up appends one fewer.
    """

    def test_the_default_as_of_is_the_display_clock(
        self, app, db, seed_user, monkeypatch,
    ):
        """The clocks are pinned APART and the count follows the display one.

        The schedule is built so exactly one period sits BETWEEN the two clocks:
        it has ended on the process clock (2026-07-31) and has not on the display
        clock (2026-07-30, its own last covered day).  The two counts therefore
        differ by exactly one, and both are asserted -- the process-clock number
        is computed here rather than assumed, so the case cannot pass on a
        schedule where the two happen to agree.
        """
        owner_day = date(2026, 7, 30)
        # Named once and threaded, so the schedule the writer builds and the
        # cadence the counter derives the LAST period's end from cannot come
        # apart -- which is the pairing plan step C4 made explicit when the
        # counter stopped reading a stored ``end_date``.
        cadence_days = 14
        with app.app_context():
            user_id = seed_user["user"].id
            record_paydays_across_a_hole(
                user_id, date(2026, 7, 3), 4, rhythm_of(cadence_days),
            )
            db.session.commit()

            # pylint: disable=protected-access
            facts = pay_schedule_service.ScheduleFacts(
                (era_of(date(2026, 7, 3), cadence_days),), None,
            )
            on_process = pay_period_rolling._future_period_count(
                user_id, facts, date(2026, 7, 31),
            )
            on_owner = pay_period_rolling._future_period_count(
                user_id, facts, owner_day,
            )
            assert on_owner == on_process + 1, (on_owner, on_process)

            freeze_today(monkeypatch, date(2026, 7, 31))
            monkeypatch.setattr(
                pay_period_rolling, "display_today", lambda: owner_day,
            )
            pay_schedule_service.set_rolling(
                user_id, enabled=True, target_periods=on_owner,
            )
            db.session.commit()

            # The window is FULL on the owner's clock and one short on the
            # process clock, so a door reading the process clock appends one.
            assert pay_period_rolling.top_up_rolling_window(user_id) == []


class TestTheCadenceThreadedIsTheOWNERSStoredOne:
    """The cadence the door passes is graded, not just the day and the paydays.

    The cadence decides ONE thing in the count -- the LAST period's end, which
    is ``start_date + cadence_days - 1`` where every other end is dictated by
    the next payday.  So a test whose ``as_of`` falls outside that last
    projected span cannot see the argument at all, and every other case in this
    file is such a test: they would pass unchanged if
    :func:`top_up_rolling_window` threaded any other in-range number, including
    ``rolling_target_periods``, whose column default is 52.

    **The fixture is ledger row P28's shape**, which is why it is buildable:
    the paydays are recorded at cadence 14 and the STORED cadence is then moved
    to 3, so the horizon shortens while no payday moves.  That is a legacy
    state -- since plan step C3-b only a batch that records a payday may set
    the cadence -- and it is the one state in which "which cadence did you
    use?" has an observable answer.
    """

    #: Paydays 2026-07-03, -07-17 and -07-31, recorded at cadence 14.  The last
    #: period's end is the only one the cadence decides: 08-13 at 14, 08-02 at
    #: 3.  ``_PROBE_DAY`` sits BETWEEN them, so the two answers differ by one.
    _STORED_CADENCE = 3
    _PROBE_DAY = date(2026, 8, 10)

    def _diverged_cadence(self, db_session, seed_user):
        """Record three biweekly paydays, then shorten the STORED cadence to 3.

        Args:
            db_session: The test ``db.session``.
            seed_user: The seeded owner fixture.

        Returns:
            The owner's user id.
        """
        user_id = seed_user["user"].id
        record_paydays_across_a_hole(user_id, _FUTURE_START, 3, rhythm_of(14))
        # **A cadence change is a NEW ERA**, and its day is its phase (plan
        # step ``pay_calendar:C17-a``, ruling **R-PC58**): a 3-day grid
        # phased on the 14-day batch's opening would run 07-30, 08-02, and
        # 08-02 falls INSIDE the paycheck opened by the recorded 07-31, which
        # ``reject_backward_payday`` refuses.  So the era takes effect on the
        # last recorded payday -- what ``record_paydays`` would have minted
        # for a batch stated at the new cadence from there -- which is the
        # phase the extend continues.  The old row held the cadence and the
        # phase as two columns, which was ledger row **N-492**.
        pay_era_write.mint_era(
            user_id,
            era_of(_FUTURE_START + timedelta(days=28), self._STORED_CADENCE),
        )
        db_session.commit()
        return user_id

    def test_the_count_moves_with_the_cadence_it_is_given(
        self, app, db, seed_user,
    ):
        """Same owner, same day, two cadences, two answers -- 0 and 1.

        The FIRING CONTROL for the door case below: it shows the probe day
        really does straddle the two projected ends, so the door assertion is
        about which cadence was threaded rather than about an insensitive day.
        """
        with app.app_context():
            user_id = self._diverged_cadence(db.session, seed_user)

            # pylint: disable=protected-access
            assert pay_period_rolling._future_period_count(
                user_id,
                pay_schedule_service.ScheduleFacts(
                    (era_of(_FUTURE_START, self._STORED_CADENCE),), None,
                ),
                self._PROBE_DAY,
            ) == 0
            assert pay_period_rolling._future_period_count(
                user_id,
                pay_schedule_service.ScheduleFacts(
                    (era_of(_FUTURE_START, 14),), None,
                ),
                self._PROBE_DAY,
            ) == 1

    def test_the_door_threads_the_STORED_cadence(
        self, app, db, seed_user, monkeypatch,
    ):
        """Target 1: the stored cadence 3 is one short, so exactly one is added.

        With the owner's own cadence the window holds ZERO current-and-future
        paychecks on the probe day and the top-up appends one.  A door that
        threaded 14 instead -- the cadence the paydays were GENERATED at, and
        the number every other case in this file would accept -- would see a
        full window and write nothing.
        """
        with app.app_context():
            user_id = self._diverged_cadence(db.session, seed_user)
            monkeypatch.setattr(
                pay_period_rolling, "display_today", lambda: self._PROBE_DAY,
            )
            pay_schedule_service.set_rolling(
                user_id, enabled=True, target_periods=1,
            )
            db.session.commit()
            before = len(all_periods(user_id))

            assert len(pay_period_rolling.top_up_rolling_window(user_id)) == 1
            assert len(all_periods(user_id)) == before + 1
            assert_pay_period_invariants(db.session, user_id)
