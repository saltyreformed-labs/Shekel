"""Tests for pay-period CRUD Phase 2b: the continuous rolling top-up.

``top_up_rolling_window`` keeps a target number of current-and-future
pay periods generated ahead of today.  It is called on every grid /
dashboard load, so the common (disabled / already-full) paths must be
cheap and side-effect-free, and the deficit path must create EXACTLY the
shortfall, idempotently and without ever landing a duplicate
``period_index``.

**It RETURNS the periods it appended and leaves them EMPTY, which is ruling
R-R38** (plan step R7d-c-1).  The recurring rows are generated by the caller,
in a read pass only the route layer may open, so every case here that asserts
ROWS runs ``_top_up_and_populate`` -- what ``/grid`` and ``/dashboard``
actually run -- and every case about the top-up's own contract compares
against a LIST of periods rather than a count.

Because a pay period is the spine of every financial number, the
deficit-path tests assert all four disciplines: structural invariants
(Discipline 1, ``assert_pay_period_invariants``), hand-computed as-of
balances continuing into the new window (Discipline 2), and the
production integrity checker passing (Discipline 3).  The advisory lock is
asserted by capturing the emitted SQL: since plan step ``balance:X-bn`` the
top-up takes none of its own on any path, and ``/grid``'s ``write_transaction``
block takes the owner's at its first statement, rolling or not (rulings
**R-CC114**, **R-CC115**).  *Until that step the top-up took it on a real
deficit and never on the disabled / full fast paths.*  Concurrency /
idempotency under true parallel requests lives in
``tests/test_concurrent/test_race_conditions.py``.  See
``docs/plans/implementation_plan_pay_period_crud.md``.
"""
